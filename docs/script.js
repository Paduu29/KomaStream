const supportedLocales = ["en", "de", "es"];
const storageKey = "komastream-language";

function getByPath(source, path) {
  return path.split(".").reduce((value, key) => (value && key in value ? value[key] : undefined), source);
}

function chooseLocale() {
  try {
    const stored = localStorage.getItem(storageKey);
    if (stored && supportedLocales.includes(stored)) {
      return stored;
    }
  } catch {
    // Ignore storage access failures and fall back to browser language.
  }

  const browserLanguages = Array.isArray(navigator.languages) && navigator.languages.length > 0
    ? navigator.languages
    : [navigator.language || "en"];

  const browserMatch = browserLanguages.find((language) => {
    const base = language.toLowerCase().split("-")[0];
    return supportedLocales.includes(base);
  });

  return browserMatch ? browserMatch.toLowerCase().split("-")[0] : "en";
}

function setTextContent(selector, localeData) {
  document.querySelectorAll(selector).forEach((element) => {
    const key = element.dataset.i18n;
    const value = getByPath(localeData, key);
    if (typeof value === "string") {
      element.textContent = value;
    }
  });
}

function setAttributeContent(selector, attribute, localeData) {
  document.querySelectorAll(selector).forEach((element) => {
    const key = element.getAttribute(`data-i18n-${attribute}`);
    const value = getByPath(localeData, key);
    if (typeof value === "string") {
      element.setAttribute(attribute, value);
    }
  });
}

function applyLocale(locale) {
  const localeData = translations[locale] || translations.en;

  document.documentElement.lang = locale;
  document.title = localeData.meta.title;

  const description = document.querySelector('meta[name="description"]');
  if (description) {
    description.setAttribute("content", localeData.meta.description);
  }

  const ogDescription = document.querySelector('meta[property="og:description"]');
  if (ogDescription) {
    ogDescription.setAttribute("content", localeData.meta.ogDescription);
  }

  setTextContent("[data-i18n]", localeData);
  setAttributeContent("[data-i18n-aria-label]", "aria-label", localeData);
  setAttributeContent("[data-i18n-alt]", "alt", localeData);
  setAttributeContent("[data-i18n-title]", "title", localeData);
  setAttributeContent("[data-i18n-placeholder]", "placeholder", localeData);
  setAttributeContent("[data-i18n-content]", "content", localeData);

  const languageSelect = document.getElementById("language-select");
  if (languageSelect && languageSelect.value !== locale) {
    languageSelect.value = locale;
  }

  try {
    localStorage.setItem(storageKey, locale);
  } catch {
    // Ignore storage access failures.
  }
}

const languageSelect = document.getElementById("language-select");
const initialLocale = chooseLocale();

if (languageSelect) {
  languageSelect.addEventListener("change", (event) => {
    const nextLocale = supportedLocales.includes(event.target.value) ? event.target.value : "en";
    applyLocale(nextLocale);
  });
}

applyLocale(initialLocale);
